// The migrated schema as plain SQL, for e2e/support/sqlFixture.mjs: a fresh database run through every table
// migration and nothing else (no repository attached, no seed imported), dumped as CREATE and INSERT statements.
// The e2e fixture writer loads that file instead of importing the server, so the batteries can write their fixtures
// against any server that keeps this schema.
//
//   node scripts/sqlFixtureSchema.mjs           rewrite e2e/support/schema.sql
//   node scripts/sqlFixtureSchema.mjs --check   exit 1 if the file is out of date (testSqlFixtureSchema runs this)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DatabaseSync } from 'node:sqlite';
import { runDataMigrations } from '../repositories/database.ts';
import { DATA_MIGRATIONS } from '../repositories/index.mjs';

export const SCHEMA_FILE = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
  'e2e',
  'support',
  'schema.sql',
);

const A = 1_000_000_000_000;
const B = 2_000_000_000_000;
const migrated = (now) => {
  const db = new DatabaseSync(':memory:');
  db.exec('PRAGMA foreign_keys = ON;');
  runDataMigrations(db, DATA_MIGRATIONS, { now });
  return db;
};
const literal = (v) => {
  if (v === null) return 'NULL';
  if (typeof v === 'number' || typeof v === 'bigint') return String(v);
  if (v instanceof Uint8Array) return `X'${Buffer.from(v).toString('hex')}'`;
  return `'${String(v).replaceAll("'", "''")}'`;
};

/**
 * The dump of a freshly migrated database. A value the migrations derive from their clock (a seeded row's creation
 * time, a challenge's end) is written as `__NOW__ + offset`, found by migrating twice at two clocks; the fixture
 * writer substitutes its own clock, so a fresh fixture looks migrated just now, as a first boot's would.
 */
export function migratedSchemaSql() {
  const db = migrated(A);
  const other = migrated(B);
  try {
    const objects = db.prepare('SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL ORDER BY rowid').all();
    const tables = objects.filter((o) => o.type === 'table' && o.name !== 'sqlite_sequence');
    const out = [
      '-- Generated by scripts/sqlFixtureSchema.mjs from the table migrations. Do not edit: regenerate it.',
      '-- __NOW__ stands for the clock of the fixture that loads it.',
      'BEGIN;',
    ];
    for (const t of tables) out.push(`${t.sql};`);
    for (const t of tables) {
      const cols = db
        .prepare(`PRAGMA table_xinfo("${t.name}")`)
        .all()
        .filter((c) => c.hidden === 0)
        .map((c) => `"${c.name}"`);
      const select = `SELECT ${cols.join(', ')} FROM "${t.name}"`;
      const rows = db.prepare(select).all();
      const otherRows = other.prepare(select).all();
      if (rows.length !== otherRows.length)
        throw new Error(`${t.name}: the migrations seed a clock-dependent row count`);
      rows.forEach((row, i) => {
        const values = Object.keys(row).map((k) => {
          const [a, b] = [row[k], otherRows[i][k]];
          if (a === b) return literal(a);
          if (typeof a === 'number' && typeof b === 'number' && a - A === b - B)
            return a === A ? '__NOW__' : `(__NOW__ + ${a - A})`;
          throw new Error(`${t.name}.${k}: a seeded value that is neither fixed nor an offset from the clock`);
        });
        out.push(`INSERT INTO "${t.name}" (${cols.join(', ')}) VALUES (${values.join(', ')});`);
      });
    }
    if (objects.some((o) => o.name === 'sqlite_sequence'))
      for (const r of db.prepare('SELECT name, seq FROM sqlite_sequence ORDER BY name').all())
        out.push(`INSERT INTO sqlite_sequence (name, seq) VALUES (${literal(r.name)}, ${r.seq});`);
    for (const type of ['index', 'trigger', 'view'])
      for (const o of objects.filter((x) => x.type === type)) out.push(`${o.sql};`);
    out.push('COMMIT;', '');
    return out.join('\n');
  } finally {
    db.close();
    other.close();
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const sql = migratedSchemaSql();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(SCHEMA_FILE) ? fs.readFileSync(SCHEMA_FILE, 'utf8') : '';
    if (current !== sql) {
      console.error(`✗ ${SCHEMA_FILE} is out of date: run node scripts/sqlFixtureSchema.mjs`);
      process.exit(1);
    }
    console.log('✓ e2e/support/schema.sql matches the table migrations');
  } else {
    fs.writeFileSync(SCHEMA_FILE, sql);
    console.log(`wrote ${SCHEMA_FILE} (${sql.length} bytes)`);
  }
}
