// Writes src/scoutbox/rules/time_zones.gleam: the time-zone names the TypeScript server accepts
// (temporal.ts `validateIanaZone`), taken by asking that rule about every name Node's time-zone data knows.
// OTP has no IANA time-zone database, and no maintained Gleam package provides one.
//   node dev/time_zones.mjs && gleam format src/scoutbox/rules/time_zones.gleam
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const temporal = await import(path.join(HERE, '../../../scoutbox/scoutbox-server/temporal.ts'));
const candidates = new Set([...Intl.supportedValuesOf('timeZone'), 'UTC', 'Etc/UTC', 'GMT', 'Etc/GMT']);
for (const k of Object.keys(temporal.MODERN_ZONE_ALIASES ?? {})) candidates.add(k);
const accepted = [...candidates].filter((z) => temporal.validateIanaZone(z).ok).sort();
const out = path.join(HERE, '../src/scoutbox/rules/time_zones.gleam');
fs.writeFileSync(
  out,
  `//// Generated by dev/time_zones.mjs from the TypeScript server's validateIanaZone. Don't edit.\n\n` +
    `/// The IANA time-zone names a preference may name.\npub const names = [${accepted.map((z) => JSON.stringify(z)).join(', ')}]\n`,
);
console.log(`wrote ${accepted.length} zone names`);
