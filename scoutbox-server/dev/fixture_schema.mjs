// Writes e2e/support/schema.sql, the migrated schema the batteries' fixtures load (e2e/support/sqlFixture.mjs):
// every migration in priv/migrations applied to an empty database as the server's runner applies them, then dumped
// in creation order (tables, their rows, then indexes and triggers), the migrations' clock written back as __NOW__ for the fixture's own.
//
//   node dev/fixture_schema.mjs           rewrite it
//   node dev/fixture_schema.mjs --check   fail if it is out of date (part of `npm run e2e:check`)
import fs from 'node:fs';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const MIGRATIONS = path.join(root, 'priv', 'migrations');
const OUT = path.join(root, 'e2e', 'support', 'schema.sql');
// A clock no fixture or migration would write, so every occurrence is the migrations' own.
const NOW = '7357735773577';
// The default session lifetime (config.gleam), as the server fills it in.
const SESSION_TTL_MS = '2592000000';
const TEN_YEARS_MS = 10 * 365 * 86_400_000;

const db = new DatabaseSync(':memory:');
db.exec('PRAGMA foreign_keys = ON');
db.exec('CREATE TABLE data_migrations (id TEXT PRIMARY KEY, applied_at INTEGER NOT NULL);');
db.exec('CREATE TABLE meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);');
for (const file of fs
  .readdirSync(MIGRATIONS)
  .filter((f) => f.endsWith('.sql'))
  .sort()) {
  const sql = fs.readFileSync(path.join(MIGRATIONS, file), 'utf8');
  const fkOff = sql.includes('\n-- foreign_keys: off\n');
  if (fkOff) db.exec('PRAGMA foreign_keys = OFF');
  db.exec('BEGIN');
  db.exec(sql.replaceAll('__NOW__', NOW).replaceAll('__SESSION_TTL_MS__', SESSION_TTL_MS));
  db.prepare('INSERT INTO data_migrations (id, applied_at) VALUES (?, ?)').run(file.slice(0, -4), Number(NOW));
  db.exec('COMMIT');
  if (fkOff) db.exec('PRAGMA foreign_keys = ON');
}

const literal = (v) => {
  if (v === null) return 'NULL';
  if (typeof v === 'number' || typeof v === 'bigint') {
    // A migration may write a time relative to its clock (`__NOW__ + 604800000`); nothing else is near it.
    const d = Number(v) - Number(NOW);
    if (d === 0) return '__NOW__';
    if (Number.isInteger(d) && Math.abs(d) < TEN_YEARS_MS) return `(__NOW__ ${d > 0 ? '+' : '-'} ${Math.abs(d)})`;
    return String(v);
  }
  if (v instanceof Uint8Array) return `X'${Buffer.from(v).toString('hex').toUpperCase()}'`;
  return `'${String(v).replaceAll("'", "''")}'`.replaceAll(NOW, `'||__NOW__||'`);
};
const quote = (name) => `"${name.replaceAll('"', '""')}"`;

const objects = db
  .prepare(
    "SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY rowid",
  )
  .all();
const lines = [
  '-- Generated by dev/fixture_schema.mjs from the table migrations. Do not edit: regenerate it.',
  '-- __NOW__ stands for the clock of the fixture that loads it.',
  'BEGIN;',
  ...objects.filter((o) => o.type === 'table').map((o) => `${o.sql};`),
];
for (const { name } of objects.filter((o) => o.type === 'table')) {
  const columns = db
    .prepare(`PRAGMA table_info(${quote(name)})`)
    .all()
    .map((c) => c.name);
  const rows = db.prepare(`SELECT * FROM ${quote(name)} ORDER BY rowid`).all();
  for (const row of rows)
    lines.push(
      `INSERT INTO ${quote(name)} (${columns.map(quote).join(', ')}) VALUES (${columns.map((c) => literal(row[c])).join(', ')});`,
    );
}
// Indexes and triggers after the rows: a fixture loads faster that way, and no migration's rows need a trigger.
for (const type of ['index', 'view', 'trigger'])
  lines.push(...objects.filter((o) => o.type === type).map((o) => `${o.sql};`));
lines.push('COMMIT;', '');
const text = lines.join('\n');

if (process.argv.includes('--check')) {
  if (fs.readFileSync(OUT, 'utf8') !== text) {
    console.error('e2e/support/schema.sql is out of date with priv/migrations: run `node dev/fixture_schema.mjs`');
    process.exit(1);
  }
} else {
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(root, OUT)}: ${objects.length} objects`);
}
