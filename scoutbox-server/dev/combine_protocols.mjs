// Writes src/scoutbox/development/combine_protocols.gleam: the standardised Combine protocol registry as the
// TypeScript server serves it (`GET /org/combine/protocols`, without the Box Cam test provider), and each protocol's
// id, version, title and status. The registry is data this server keeps: Box Cam's analysis, which decides what a
// device can measure, is moving to a service of its own, so the capabilities are recorded here, not computed.
//   node dev/combine_protocols.mjs           rewrite the module
//   node dev/combine_protocols.mjs --check   exit 1 if the committed module differs
import { spawn, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { gleamString } from './battery_cases/printers.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, '..');
const TS = path.resolve(process.env.SCOUTBOX_TS_SERVER ?? path.join(ROOT, '..', '..', 'scoutbox', 'scoutbox-server'));
const OUT = path.join(ROOT, 'src', 'scoutbox', 'development', 'combine_protocols.gleam');
const { COMBINE_PROTOCOLS } = await import(pathToFileURL(path.join(TS, 'domains/development/boxcam/combineShared.mjs')).href);

const port = 23000 + Math.floor(Math.random() * 1000);
const env = { ...process.env, PORT: String(port), DATA_DIR: fs.mkdtempSync(path.join(os.tmpdir(), 'combine-')), SCOUTBOX_QUIET_LOGS: '1' };
delete env.BOX_CAM_TEST_PROVIDER;
const child = spawn(process.execPath, ['server.mjs'], { cwd: TS, env, stdio: 'ignore' });
let text;
try {
  for (let i = 0; ; i++) {
    try { if ((await fetch(`http://localhost:${port}/health`)).ok) break; } catch {}
    if (i > 120) throw new Error('the TypeScript server did not boot');
    await new Promise((r) => setTimeout(r, 250));
  }
  const login = await (await fetch(`http://localhost:${port}/auth/org/login`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ orgId: 'org-eastport', scoutName: 'Maria Keane', role: 'Head of Recruitment' }),
  })).json();
  text = await (await fetch(`http://localhost:${port}/org/combine/protocols`, { headers: { authorization: `Bearer ${login.token}` } })).text();
} finally {
  child.kill('SIGKILL');
}
JSON.parse(text);
const protocols = COMBINE_PROTOCOLS.map(
  (p) => `  Protocol(id: ${gleamString(p.id)}, version: ${p.version}, title: ${gleamString(p.title)}, active: ${p.status === 'active' ? 'True' : 'False'}),`,
).join('\n');
const source = `//// Generated by dev/combine_protocols.mjs from the TypeScript server's Combine registry. Don't edit: run
//// \`node dev/combine_protocols.mjs\`.

pub type Protocol {
  Protocol(id: String, version: Int, title: String, active: Bool)
}

pub const protocols = [
${protocols}
]

/// \`GET /org/combine/protocols\`, as the TypeScript server answers it.
pub const response = ${gleamString(text)}
`;
const formatted = spawnSync('gleam', ['format', '--stdin'], { input: source, encoding: 'utf8', cwd: ROOT });
if (formatted.status !== 0) throw new Error(formatted.stderr);
if (process.argv.includes('--check')) {
  const same = fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8') === formatted.stdout;
  if (!same) console.error('combine_protocols: src/scoutbox/development/combine_protocols.gleam differs; run node dev/combine_protocols.mjs');
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(OUT, formatted.stdout);
console.log(`combine_protocols: wrote ${COMBINE_PROTOCOLS.length} protocols`);
