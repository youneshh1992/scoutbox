// Writes priv/seed.sql: the TypeScript server's demo world, for the tables this server has. It boots the
// TypeScript server on an empty data directory (which loads its seed), stops it, and dumps the rows as INSERTs.
// Timestamps become `NOW_MS + offset` from the seed's own clock, so a first boot here seeds a world as fresh as
// the TypeScript server's; dates of birth are calendar days and stay fixed.
//
//   node dev/seed_sql.mjs     (Node ≥ 22.18; needs ../../scoutbox with its node_modules)
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DatabaseSync } from 'node:sqlite';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const TS_SERVER = path.join(HERE, '../../../scoutbox/scoutbox-server');
const MIGRATIONS = path.join(HERE, '../priv/migrations');
const OUT = path.join(HERE, '../priv/seed.sql');
// Never copied: bookkeeping. Rows the migrations themselves write are left out below.
const SKIP = new Set(['counters', 'meta', 'data_migrations']);

const data = fs.mkdtempSync(path.join(os.tmpdir(), 'scoutbox-seed-'));
const port = 20000 + Math.floor(Math.random() * 20000);
const server = spawn('node', ['server.mjs'], {
  cwd: TS_SERVER,
  env: { ...process.env, PORT: String(port), DATA_DIR: data, SCOUTBOX_QUIET_LOGS: '1' },
  stdio: 'ignore',
});
try {
  for (let i = 0; ; i++) {
    try {
      if ((await fetch(`http://localhost:${port}/health`)).ok) break;
    } catch {
      /* booting */
    }
    if (i > 120) throw new Error('the TypeScript server did not boot');
    await new Promise((r) => setTimeout(r, 250));
  }
} finally {
  server.kill('SIGTERM');
}
await new Promise((r) => server.once('exit', r));

const db = new DatabaseSync(path.join(data, 'scoutbox.db'), { readOnly: true });
// This server's tables, in migration order (so a row's references are written before it).
const ours = [];
for (const f of fs.readdirSync(MIGRATIONS).sort())
  for (const m of fs.readFileSync(path.join(MIGRATIONS, f), "utf8").matchAll(/CREATE TABLE (\w+)/g)) if (!ours.includes(m[1])) ours.push(m[1]);
// The seed's clock: the organisations are written last, at its "now".
const anchor = db.prepare('SELECT MAX(created_at) AS t FROM orgs').get().t;
const YEAR = 365 * 24 * 3600 * 1000;
const isInstant = (v) => typeof v === 'number' && Number.isInteger(v) && Math.abs(v - anchor) < 10 * YEAR;
const literal = (v, type) => {
  if (v === null) return 'NULL';
  if (typeof v === 'string') return `'${v.replaceAll("'", "''")}'`;
  if (type === 'INTEGER' && isInstant(v)) return `NOW_MS + ${v - anchor}`;
  return String(v);
};

// A freshly migrated database: the rows it already has are the migrations', not the seed's.
const migrated = new DatabaseSync(':memory:');
migrated.exec('CREATE TABLE meta (key TEXT PRIMARY KEY, value TEXT NOT NULL); CREATE TABLE data_migrations (id TEXT PRIMARY KEY, applied_at INTEGER NOT NULL);');
for (const f of fs.readdirSync(MIGRATIONS).sort())
  migrated.exec(fs.readFileSync(path.join(MIGRATIONS, f), 'utf8').replaceAll('__NOW__', '0').replaceAll('__SESSION_TTL_MS__', '0'));
const keyOf = (table) => {
  const pk = migrated.prepare('SELECT name FROM pragma_table_info(?) WHERE pk > 0 ORDER BY pk').all(table).map((c) => c.name);
  return (row) => JSON.stringify(pk.length ? pk.map((c) => row[c]) : row);
};

let sql = '-- Generated by dev/seed_sql.mjs from the TypeScript server\'s seed. NOW_MS is the first boot\'s clock.\n';
let rows = 0;
for (const table of ours) {
  if (SKIP.has(table)) continue;
  const cols = db
    .prepare('SELECT name, type, hidden FROM pragma_table_xinfo(?) ORDER BY cid')
    .all(table)
    .filter((c) => c.hidden < 2);
  const key = keyOf(table);
  const theirs = new Set(migrated.prepare(`SELECT * FROM ${table}`).all().map(key));
  for (const row of db.prepare(`SELECT * FROM ${table} ORDER BY rowid`).all()) {
    if (theirs.has(key(row))) continue;
    sql += `INSERT INTO ${table} (${cols.map((c) => c.name).join(', ')}) VALUES (${cols
      .map((c) => literal(row[c.name], c.type))
      .join(', ')});\n`;
    rows++;
  }
}
// The id counter where the seed left it, so an id minted after the seed never repeats one the seed wrote.
const counter = db.prepare("SELECT value FROM counters WHERE name = 'id'").get();
if (!counter) throw new Error("the TypeScript seed has no 'id' counter");
sql += `UPDATE counters SET value = ${counter.value} WHERE name = 'id';\n`;
fs.writeFileSync(OUT, sql);
fs.rmSync(data, { recursive: true, force: true });
console.log(`wrote ${rows} rows to ${path.relative(process.cwd(), OUT)}`);
