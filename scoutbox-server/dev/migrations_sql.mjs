// The TypeScript server's table migrations as plain SQL, one file per migration id, for priv/migrations/.
//
// Each migration is a JavaScript `up(sqlite, context)`. This runs them in order on a fresh in-memory database
// through a recorder that keeps every statement that writes (exec, and a prepared statement's run with its
// arguments inlined), so the files are exactly what a first boot of the TypeScript server does. Reads pass through
// unrecorded: on a fresh database they only steer a migration down its empty-database path, which is the only path
// this server needs (there are no old databases to upgrade).
//
// Values a migration takes from its clock are found by running twice at two clocks and written as `__NOW__ + n`.
// The session lifetime it is given is written `__SESSION_TTL_MS__`. The Gleam runner substitutes both.
//
//   node dev/migrations_sql.mjs           rewrite priv/migrations/
//   node dev/migrations_sql.mjs --check   exit 1 if priv/migrations/ differs
import fs from 'node:fs';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';

const HERE = path.dirname(new URL(import.meta.url).pathname);
const TS = path.resolve(process.env.SCOUTBOX_TS_SERVER ?? path.join(HERE, '../../../scoutbox/scoutbox-server'));
const OUT = path.join(HERE, '..', 'priv', 'migrations');
const { DATA_MIGRATIONS } = await import(path.join(TS, 'repositories', 'index.mjs'));

const A = 1_000_000_000_000;
const B = 2_000_000_000_000;
const TTL_A = 111_111_111;
const TTL_B = 222_222_222;

const literal = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number' || typeof v === 'bigint') return String(v);
  if (typeof v === 'boolean') return v ? '1' : '0';
  if (v instanceof Uint8Array) return `X'${Buffer.from(v).toString('hex')}'`;
  return `'${String(v).replaceAll("'", "''")}'`;
};

/** Mark positional (`?`) and named (`@x`, `:x`, `$x`) arguments in a statement, outside string literals. */
const inline = (sql, given) => {
  const named = given.length === 1 && given[0] && typeof given[0] === 'object' && !(given[0] instanceof Uint8Array);
  const args = [];
  let out = '';
  let quote = null;
  for (let k = 0; k < sql.length; k++) {
    const ch = sql[k];
    if (quote) {
      if (ch === quote) quote = null;
      out += ch;
    } else if (ch === "'" || ch === '"') {
      quote = ch;
      out += ch;
    } else if (ch === '?' && !named) {
      out += `\u0000${args.length}\u0000`;
      args.push(given[args.length]);
    } else if (named && '@:$'.includes(ch) && /[A-Za-z_]/.test(sql[k + 1] ?? '')) {
      const name = sql.slice(k + 1).match(/^[A-Za-z_][A-Za-z0-9_]*/)[0];
      if (!(name in given[0])) throw new Error(`no value for ${ch}${name} in: ${sql}`);
      out += `\u0000${args.length}\u0000`;
      args.push(given[0][name]);
      k += name.length;
    } else out += ch;
  }
  if (!named && args.length !== given.length) throw new Error(`argument count ${given.length} ≠ ${args.length} placeholders in: ${sql}`);
  return { text: out, args };
};

const recorder = (db, log) =>
  new Proxy(db, {
    get(target, prop) {
      if (prop === 'exec')
        return (sql) => {
          log.push({ text: sql.trim(), args: [] });
          return target.exec(sql);
        };
      if (prop === 'prepare')
        return (sql) => {
          const st = target.prepare(sql);
          return new Proxy(st, {
            get(s, p) {
              if (p === 'run')
                return (...args) => {
                  log.push(inline(sql.trim(), args));
                  return s.run(...args);
                };
              const v = s[p];
              return typeof v === 'function' ? v.bind(s) : v;
            },
          });
        };
      const v = target[prop];
      return typeof v === 'function' ? v.bind(target) : v;
    },
  });

const run = (now, sessionTtlMs) => {
  const db = new DatabaseSync(':memory:');
  db.exec('PRAGMA foreign_keys = ON;');
  db.exec('CREATE TABLE IF NOT EXISTS data_migrations (id TEXT PRIMARY KEY, applied_at INTEGER NOT NULL);');
  db.exec('CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);');
  const steps = [];
  for (const m of [...DATA_MIGRATIONS].sort((a, b) => (a.id < b.id ? -1 : 1))) {
    const log = [];
    if (m.foreignKeysOff) db.exec('PRAGMA foreign_keys = OFF;');
    db.exec('BEGIN');
    m.up(recorder(db, log), { now, sessionTtlMs });
    db.prepare('INSERT INTO data_migrations (id, applied_at) VALUES (?, ?)').run(m.id, now);
    db.exec('COMMIT');
    if (m.foreignKeysOff) db.exec('PRAGMA foreign_keys = ON;');
    steps.push({ id: m.id, note: m.note, foreignKeysOff: m.foreignKeysOff === true, log });
  }
  db.close();
  return steps;
};

const render = (a, b) => {
  if (a.log.length !== b.log.length) throw new Error(`${a.id}: the two clocks recorded different statements`);
  const lines = [`-- ${a.id}: ${a.note ?? ''}`.trimEnd(), '-- Generated by dev/migrations_sql.mjs from the TypeScript migration. Do not edit.'];
  if (a.foreignKeysOff) lines.push('-- foreign_keys: off');
  for (let i = 0; i < a.log.length; i++) {
    const x = a.log[i];
    const y = b.log[i];
    if (x.text !== y.text) throw new Error(`${a.id}: statement ${i} differs between clocks`);
    const text = x.text.replace(/\u0000(\d+)\u0000/g, (_, n) => {
      const va = x.args[Number(n)];
      const vb = y.args[Number(n)];
      if (va === vb) return literal(va);
      if (typeof va === 'number' && vb - va === B - A) return `(__NOW__ + ${va - A})`;
      if (String(va) === String(TTL_A) && String(vb) === String(TTL_B)) return typeof va === 'string' ? `'__SESSION_TTL_MS__'` : '__SESSION_TTL_MS__';
      throw new Error(`${a.id}: an argument depends on the context in a way this cannot write: ${va} / ${vb}`);
    });
    if (/\b(1|2)000000000000\b|111111111|222222222/.test(text)) throw new Error(`${a.id}: a clock value is baked into SQL text`);
    lines.push(`${text.replace(/;\s*$/, '')};`);
  }
  return `${lines.join('\n\n')}\n`;
};

const ra = run(A, TTL_A);
const rb = run(B, TTL_B);
const files = new Map(ra.map((s, i) => [`${s.id}.sql`, render(s, rb[i])]));

if (process.argv.includes('--check')) {
  const have = fs.readdirSync(OUT).filter((f) => f.endsWith('.sql'));
  const stale = [...files].filter(([f, t]) => !fs.existsSync(path.join(OUT, f)) || fs.readFileSync(path.join(OUT, f), 'utf8') !== t).map(([f]) => f);
  const extra = have.filter((f) => !files.has(f));
  if (stale.length || extra.length) {
    console.error(`priv/migrations is out of date: ${[...stale, ...extra.map((f) => `${f} (no source)`)].join(', ')}. Run node dev/migrations_sql.mjs`);
    process.exit(1);
  }
  console.log(`priv/migrations: ${files.size} migrations up to date`);
} else {
  for (const f of fs.readdirSync(OUT)) if (f.endsWith('.sql') && !files.has(f)) fs.rmSync(path.join(OUT, f));
  for (const [f, t] of files) fs.writeFileSync(path.join(OUT, f), t);
  console.log(`priv/migrations: wrote ${files.size} migrations`);
}
