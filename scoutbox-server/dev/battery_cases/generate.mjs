// Writes the generated battery tests: for every recorded call to a rule that dev/battery_cases/map.mjs maps, one
// gleeunit test calling the Gleam rule with the recorded arguments and asserting the recorded result. One file per
// battery domain and Gleam module, `test/scoutbox/battery/<domain>/<module>_test.gleam`, formatted by `gleam format`.
// Identical calls are written once. A test is named from the assertion that checked the call.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { MAP } from './map.mjs';
import { alias } from './printers.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const OUT = path.join(ROOT, 'test', 'scoutbox', 'battery');
const HEADER = '//// Generated by dev/battery_cases.mjs';

/** A Gleam test name from an assertion's message. */
function slug(message) {
  const s = message
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/^\[neg\]\s*/, 'neg ')
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, 72)
    .replace(/_+$/, '');
  return /^[a-z]/.test(s) ? s : `t_${s}`;
}

const decode = (json) => (json === undefined ? undefined : JSON.parse(json));

/**
 * Why a mapped call can't be a generated test, or null when it can: a printer refuses arguments Gleam's types can't
 * hold (a record with a field the Gleam type has no place for, text where the type is a number). Such a call is
 * ported by hand instead, and the report says why.
 */
export function unprintable(fn, call, clock) {
  const entry = MAP[fn];
  if (!entry) return null;
  try {
    entry.test(
      { args: decode(call.args), result: decode(call.result), throws: call.throws, argsAfter: decode(call.argsAfter) },
      { now: clock, use: (module) => alias(module) },
    );
    return null;
  } catch (err) {
    return `Gleam's types can't hold its arguments: ${String(err.message).replace(/ \(value .*\)$/, '')}`;
  }
}

/**
 * The generated files, as `{ file → source }`, from `cases`: every recorded call that is a case, as
 * `{ battery, fn, call, clockDependent }`. Throws when a mapped call can't be printed.
 */
export function generate(cases, clock) {
  const files = new Map();
  for (const { battery, fn, call, clockDependent } of cases) {
    const entry = MAP[fn];
    if (!entry || (clockDependent && !entry.now)) continue;
    const domain = battery.split('/')[0];
    const file = path.join(OUT, domain, `${alias(entry.module)}_test.gleam`);
    if (!files.has(file)) files.set(file, { batteries: new Set(), imports: new Set(), tests: [], names: new Set(), seen: new Set() });
    const f = files.get(file);
    const key = JSON.stringify([fn, call.args, call.result, call.throws, call.argsAfter]);
    if (f.seen.has(key)) continue;
    f.seen.add(key);
    f.batteries.add(battery);
    const ctx = {
      now: clock,
      use: (module) => {
        f.imports.add(module);
        return alias(module);
      },
    };
    let body;
    try {
      body = entry.test(
        { args: decode(call.args), result: decode(call.result), throws: call.throws, argsAfter: decode(call.argsAfter) },
        ctx,
      );
    } catch (err) {
      throw new Error(`${battery}: ${fn} (${call.assertion ?? 'no assertion'}): ${err.message}`);
    }
    const base = slug(call.assertion ?? fn.split('#')[1]);
    let name = base;
    for (let n = 2; f.names.has(name); n++) name = `${base}_${n}`;
    f.names.add(name);
    const what = `${battery.split('/').slice(1).join('/')}: ${fn.split('#')[1]}${call.assertion ? ` — ${call.assertion}` : ''}`;
    f.tests.push(`// ${what.replace(/\n/g, ' ')}\npub fn ${name}_test() {\n  ${body}\n}`);
  }
  const out = new Map();
  for (const [file, f] of files) {
    const body = f.tests.join('\n\n');
    const unqualified = ['None', 'Some'].filter((c) => new RegExp(`\\b${c}\\b`).test(body));
    // A module a printer used qualified is imported once, with the unqualified constructors when the body has any.
    const imports = [...new Set([...f.imports, ...(unqualified.length ? ['gleam/option'] : [])])]
      .sort()
      .map((m) => (m === 'gleam/option' && unqualified.length ? `import gleam/option.{${unqualified.join(', ')}}` : `import ${m}`));
    const text = [
      `${HEADER} from the TypeScript rules suites of ${[...f.batteries].sort().join(', ')}`,
      '//// (scripts/rules/ in the TypeScript server). Don\'t edit: change the rule or the suite, then run `npm run cases`.',
      '',
      ...imports,
      '',
      body,
      '',
    ].join('\n');
    const formatted = spawnSync('gleam', ['format', '--stdin'], { input: text, encoding: 'utf8', cwd: ROOT });
    if (formatted.status !== 0) throw new Error(`gleam format refused ${path.relative(ROOT, file)}:\n${formatted.stderr}\n${text}`);
    out.set(file, formatted.stdout);
  }
  return out;
}

/** Generated files already on disk (those that start with the header). */
export function existing() {
  if (!fs.existsSync(OUT)) return [];
  return fs
    .readdirSync(OUT, { recursive: true })
    .map((f) => path.join(OUT, f))
    .filter((f) => f.endsWith('_test.gleam') && fs.readFileSync(f, 'utf8').startsWith(HEADER));
}
